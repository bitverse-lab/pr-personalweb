import { index, integer, pgTable, text, timestamp, uuid } from "drizzle-orm/pg-core";
import { users } from "./auth";
import { applications } from "./career";

export type MediaBucket = "public-media" | "private-docs";
export type MediaKind = "image" | "document";
export type MediaStatus = "pending" | "ready";
export type MediaPurpose = "editor" | "cover" | "profile" | "document" | "library";
export type DocumentType = "cv" | "cover_letter" | "offer" | "other";

const userRef = () =>
  text("user_id")
    .notNull()
    .references(() => users.id, { onDelete: "cascade" });

// One row per uploaded object. The storage key is generated by the server; the client filename is display-only.
export const media = pgTable(
  "media",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: userRef(),
    bucket: text("bucket").$type<MediaBucket>().notNull(),
    storageKey: text("storage_key").notNull().unique(),
    originalName: text("original_name").notNull(),
    mimeType: text("mime_type").notNull(),
    sizeBytes: integer("size_bytes").notNull(),
    kind: text("kind").$type<MediaKind>().notNull(),
    purpose: text("purpose").$type<MediaPurpose>().notNull().default("library"),
    // "pending" until the server has verified the uploaded bytes
    status: text("status").$type<MediaStatus>().notNull().default("pending"),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => [index("media_user_created_idx").on(t.userId, t.createdAt)]
);

export const applicationDocuments = pgTable("application_document", {
  id: uuid("id").primaryKey().defaultRandom(),
  userId: userRef(),
  applicationId: uuid("application_id")
    .notNull()
    .references(() => applications.id, { onDelete: "cascade" }),
  mediaId: uuid("media_id")
    .notNull()
    .references(() => media.id, { onDelete: "cascade" }),
  type: text("type").$type<DocumentType>().notNull().default("other"),
  note: text("note"),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
});
